#!/usr/bin/env node
/**
 * Knot UI CLI. Zero dependencies on purpose — it runs before anything is
 * installed, so it may only use Node builtins.
 *
 *   npx knotui init                    scaffold knot.config.json + theme.css
 *   npx knotui add accordion tabs      install components one at a time
 *   npx knotui theme --hue 274         regenerate the palette
 *   npx knotui list                    show the component registry
 */
import { execSync } from 'node:child_process';
import { createInterface } from 'node:readline/promises';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REGISTRY = JSON.parse(readFileSync(join(HERE, '..', 'registry.json'), 'utf8'));
const CONFIG_FILE = 'knot.config.json';

const c = {
  dim: (s) => `\x1b[2m${s}\x1b[0m`,
  bold: (s) => `\x1b[1m${s}\x1b[0m`,
  accent: (s) => `\x1b[38;5;141m${s}\x1b[0m`,
  ok: (s) => `\x1b[32m${s}\x1b[0m`,
  warn: (s) => `\x1b[33m${s}\x1b[0m`,
  err: (s) => `\x1b[31m${s}\x1b[0m`,
};

/* ------------------------------------------------------------------ palette */

// Lightness/chroma ramp, tuned once for perceptual evenness. Only the hue moves,
// which is why any hue produces a usable, WCAG-workable scale.
const RAMP = [
  [50, 0.977, 0.014],
  [100, 0.946, 0.033],
  [200, 0.902, 0.063],
  [300, 0.828, 0.111],
  [400, 0.714, 0.163],
  [500, 0.606, 0.201],
  [600, 0.541, 0.223],
  [700, 0.491, 0.216],
  [800, 0.432, 0.181],
  [900, 0.38, 0.146],
  [950, 0.283, 0.101],
];

const GRAY_RAMP = [
  [50, 0.985, 0.002],
  [100, 0.967, 0.003],
  [200, 0.928, 0.006],
  [300, 0.872, 0.01],
  [400, 0.707, 0.015],
  [500, 0.551, 0.019],
  [600, 0.446, 0.021],
  [700, 0.373, 0.023],
  [800, 0.279, 0.023],
  [900, 0.21, 0.021],
  [950, 0.145, 0.017],
];

const PRESETS = {
  violet: 274,
  indigo: 268,
  blue: 245,
  cyan: 210,
  teal: 185,
  emerald: 158,
  green: 145,
  lime: 125,
  amber: 78,
  orange: 55,
  rose: 15,
  pink: 350,
  fuchsia: 320,
  purple: 300,
};

function ramp(name, hue, rows, intensity = 1) {
  return rows
    .map(([step, l, ch]) => `  --knot-${name}-${step}: oklch(${l} ${(ch * intensity).toFixed(3)} ${hue});`)
    .join('\n');
}

function themeCss({ hue, grayHue, intensity, radius }) {
  return `/* Generated by \`npx knotui theme\`. Safe to edit; re-running overwrites it.
   Import AFTER @knotui/core/styles.css so these win. */
:root {
${ramp('primary', hue, RAMP, intensity)}

${ramp('neutral', grayHue, GRAY_RAMP)}
}

:root { --knot-radius-scale: ${{ none: 0, sm: 0.6, md: 1, lg: 1.5, full: 2.4 }[radius]}; }
`;
}

/* -------------------------------------------------------------------- utils */

const arg = (argv, name, fallback) => {
  const i = argv.indexOf(`--${name}`);
  return i === -1 ? fallback : argv[i + 1];
};
const flag = (argv, name) => argv.includes(`--${name}`);

function readConfig() {
  return existsSync(CONFIG_FILE) ? JSON.parse(readFileSync(CONFIG_FILE, 'utf8')) : null;
}

function writeConfig(cfg) {
  writeFileSync(CONFIG_FILE, JSON.stringify(cfg, null, 2) + '\n');
}

function detectPackageManager() {
  if (existsSync('pnpm-lock.yaml')) return 'pnpm';
  if (existsSync('yarn.lock')) return 'yarn';
  if (existsSync('bun.lockb')) return 'bun';
  return 'npm';
}

function install(packages, { dryRun }) {
  const pm = detectPackageManager();
  const cmd = pm === 'npm' ? `npm install ${packages.join(' ')}` : `${pm} add ${packages.join(' ')}`;
  console.log(c.dim(`  $ ${cmd}`));
  if (dryRun) return;
  execSync(cmd, { stdio: 'inherit' });
}

/** Best-effort: find the app entry so we can append the CSS import for them. */
function findEntry() {
  const candidates = [
    'src/main.tsx', 'src/main.ts', 'src/main.jsx', 'src/index.tsx', 'src/index.jsx',
    'app/layout.tsx', 'src/app/layout.tsx', 'src/App.tsx', 'pages/_app.tsx',
  ];
  return candidates.find((f) => existsSync(f)) ?? null;
}

function ensureImport(file, spec) {
  const src = readFileSync(file, 'utf8');
  if (src.includes(spec)) return false;
  writeFileSync(file, `import '${spec}';\n${src}`);
  return true;
}

/* ----------------------------------------------------------------- commands */

async function init(argv) {
  const interactive = process.stdin.isTTY && !flag(argv, 'yes');
  let hue = arg(argv, 'hue');
  let radius = arg(argv, 'radius', 'md');
  let grayHue = arg(argv, 'gray', '264');
  let intensity = Number(arg(argv, 'intensity', '1'));

  if (interactive && !hue) {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    console.log(c.bold('\n  Knot UI setup\n'));
    console.log('  Palettes: ' + Object.keys(PRESETS).join(', '));
    const chosen = (await rl.question(c.accent('  Brand color [violet]: '))).trim() || 'violet';
    hue = PRESETS[chosen] ?? chosen;
    radius = (await rl.question(c.accent('  Corner radius none|sm|md|lg|full [md]: '))).trim() || 'md';
    await rl.close();
  }

  hue = Number(hue ?? PRESETS.violet);
  if (!Number.isFinite(hue)) hue = PRESETS.violet;
  if (!['none', 'sm', 'md', 'lg', 'full'].includes(radius)) radius = 'md';

  const cfg = {
    $schema: 'https://knotui.dev/config.schema.json',
    theme: { hue, grayHue: Number(grayHue), intensity, radius },
    cssPath: arg(argv, 'css', 'src/knot-theme.css'),
    components: [],
  };
  writeConfig(cfg);
  emitTheme(cfg);

  console.log(`\n  ${c.ok('created')} ${CONFIG_FILE}`);
  install([REGISTRY.core.package], { dryRun: flag(argv, 'dry-run') });

  const entry = findEntry();
  const lines = [`import '${REGISTRY.core.styles}';`, `import './${cfg.cssPath.split('/').pop()}';`];
  if (entry && !flag(argv, 'dry-run')) {
    ensureImport(entry, `./${cfg.cssPath.split('/').pop()}`);
    ensureImport(entry, REGISTRY.core.styles);
    console.log(`  ${c.ok('wired')}  ${entry}`);
  } else {
    console.log(`\n  Add to your entry file:\n${lines.map((l) => '    ' + c.dim(l)).join('\n')}`);
  }

  console.log(`\n  Next: ${c.accent('npx knotui add accordion')}\n`);
}

function emitTheme(cfg) {
  const path = resolve(cfg.cssPath);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, themeCss(cfg.theme));
  console.log(`  ${c.ok('theme')}   ${cfg.cssPath}`);
}

function theme(argv) {
  const cfg = readConfig();
  if (!cfg) return fail(`no ${CONFIG_FILE}. Run \`npx knotui init\` first.`);
  const preset = arg(argv, 'preset');
  cfg.theme = {
    ...cfg.theme,
    hue: Number(arg(argv, 'hue', preset ? PRESETS[preset] : cfg.theme.hue)),
    grayHue: Number(arg(argv, 'gray', cfg.theme.grayHue)),
    intensity: Number(arg(argv, 'intensity', cfg.theme.intensity)),
    radius: arg(argv, 'radius', cfg.theme.radius),
  };
  writeConfig(cfg);
  emitTheme(cfg);
}

function add(argv) {
  const names = argv.filter((a) => !a.startsWith('--'));
  if (names.length === 0) return fail('nothing to add. Try `npx knotui add accordion`.');

  const cfg = readConfig();
  const wanted = names.includes('all') ? REGISTRY.components.map((x) => x.name) : names;
  const found = [];
  for (const name of wanted) {
    const entry = REGISTRY.components.find((x) => x.name === name);
    if (!entry) {
      console.log(`  ${c.warn('skip')}    ${name} — not in the registry yet`);
      continue;
    }
    found.push(entry);
  }
  if (found.length === 0) return;

  install(found.map((f) => f.package), { dryRun: flag(argv, 'dry-run') });

  const entryFile = flag(argv, 'dry-run') ? null : findEntry();
  for (const f of found) {
    if (entryFile) ensureImport(entryFile, f.styles);
    console.log(`  ${c.ok('added')}   ${c.bold(f.name)}  ${c.dim(f.snippet)}`);
  }
  if (entryFile) console.log(`  ${c.ok('styles')}  imported in ${entryFile}`);
  else console.log(`\n  Import styles:\n${found.map((f) => c.dim(`    import '${f.styles}';`)).join('\n')}`);

  if (cfg) {
    cfg.components = [...new Set([...(cfg.components ?? []), ...found.map((f) => f.name)])];
    writeConfig(cfg);
  }
  console.log('');
}

function list() {
  console.log(c.bold('\n  Available\n'));
  for (const x of REGISTRY.components) {
    console.log(`  ${c.accent(x.name.padEnd(14))}${x.description}`);
    console.log(`  ${''.padEnd(14)}${c.dim(`variants: ${x.variants.join(', ')} · hook: ${x.hook}()`)}`);
  }
  console.log(c.bold('\n  Planned\n'));
  console.log('  ' + c.dim(REGISTRY.planned.join(', ')) + '\n');
}

function help() {
  console.log(`
  ${c.bold('knotui')} ${c.dim('— configuration-driven React UI')}

  ${c.accent('init')}     [--hue 274] [--radius md] [--gray 264] [--yes]
  ${c.accent('add')}      <component…|all> [--dry-run]
  ${c.accent('theme')}    [--preset violet] [--hue 274] [--radius lg] [--intensity 1]
  ${c.accent('list')}

  Palette presets: ${c.dim(Object.keys(PRESETS).join(', '))}
`);
}

function fail(msg) {
  console.error(`  ${c.err('error')}   ${msg}`);
  process.exitCode = 1;
}

const [command, ...rest] = process.argv.slice(2);
switch (command) {
  case 'init': await init(rest); break;
  case 'add': add(rest); break;
  case 'theme': theme(rest); break;
  case 'list': list(); break;
  case undefined:
  case 'help':
  case '--help':
  case '-h': help(); break;
  default: fail(`unknown command \`${command}\``), help();
}
